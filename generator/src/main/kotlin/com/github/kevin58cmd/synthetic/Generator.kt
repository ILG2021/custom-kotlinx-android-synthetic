package com.github.kevin58cmd.synthetic

import org.w3c.dom.Element
import java.nio.channels.FileChannel
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.StandardCopyOption
import java.nio.file.StandardOpenOption
import javax.xml.XMLConstants
import javax.xml.parsers.DocumentBuilderFactory

/** Layers are ordered from lowest to highest priority; roots within a layer are peers. */
data class GenerationSpec(
    val namespace: String,
    val resourceLayers: List<List<Path>>,
    val output: Path,
    val androidX: Boolean = true,
    // Retained for existing callers and IDE models; standalone holder extensions are no longer generated.
    val viewHolders: Boolean = false,
    val platformFragments: Boolean = false,
    val typeOverrides: Map<String, String> = emptyMap(),
    val classpath: List<Path> = emptyList(),
    val javaSourceRoots: List<Path> = emptyList(),
)

object Generator {
    private const val HEADER = "// Generated by synthetic-compat. Do not edit."
    private const val ANDROID = "http://schemas.android.com/apk/res/android"
    private val locks = Array(64) { Any() }
    private val identifier = Regex("[A-Za-z_][A-Za-z0-9_]*")
    private data class Id(val name: String, val framework: Boolean)
    private data class Include(val layout: String, val id: Id?)
    private data class Layout(val views: Map<Id, String>, val includes: List<Include>, val isMerge: Boolean, val isDefault: Boolean)

    /** Parse before changing output. IDE and Gradle serialize writes across processes. */
    fun generate(spec: GenerationSpec): List<String> {
        val output = spec.output.toAbsolutePath().normalize()
        synchronized(locks[(output.hashCode() and Int.MAX_VALUE) % locks.size]) {
            Files.createDirectories(output.parent)
            FileChannel.open(output.resolveSibling(".${output.fileName}.lock"),
                StandardOpenOption.CREATE, StandardOpenOption.WRITE).use { channel ->
                channel.lock().use { return generateLocked(spec.copy(output = output)) }
            }
        }
    }

    private fun generateLocked(spec: GenerationSpec): List<String> {
        require(spec.namespace.split('.').all { identifier.matches(it) }) { "Invalid namespace: ${spec.namespace}" }
        val diagnostics = linkedSetOf<String>()
        val selected = linkedMapOf<String, Path>()
        for (layer in spec.resourceLayers) {
            val peers = linkedMapOf<String, Path>()
            for (root in layer) {
                if (!Files.isDirectory(root)) continue
                Files.list(root).use { dirs ->
                    dirs.filter { Files.isDirectory(it) && (it.fileName.toString() == "layout" || it.fileName.toString().startsWith("layout-")) }
                        .sorted().forEach { dir ->
                            Files.list(dir).use { files ->
                                files.filter { it.fileName.toString().endsWith(".xml") }.sorted().forEach { file ->
                                    val key = "${dir.fileName}/${file.fileName}"
                                    val previous = peers.putIfAbsent(key, file)
                                    require(previous == null || previous == file) { "Duplicate resource $key at equal priority: $previous and $file" }
                                }
                            }
                        }
                }
            }
            selected.putAll(peers)
        }
        val types = ViewTypes(spec.classpath, spec.javaSourceRoots)
        val layouts = selected.values.groupBy { it.fileName.toString().removeSuffix(".xml") }
            .mapValues { (_, files) -> files.map { parse(it, spec, types) } }
        // Like legacy synthetics, each package exposes only IDs declared in its own XML.
        val optionalIds = mutableMapOf<String, Set<Id>>()
        fun resolve(name: String): Map<Id, String> {
            val alternatives = layouts.getValue(name)
            val merged = linkedMapOf<Id, String>()
            var required: Set<Id>? = null
            fun add(id: Id, type: String) {
                val previous = merged[id]
                if (previous != null && previous != type) {
                    merged[id] = "android.view.View"
                    diagnostics += "$name: '${id.name}' has differing types across layouts; using android.view.View."
                } else merged[id] = type
            }
            for (layout in alternatives) {
                val present = linkedSetOf<Id>()
                layout.includes.forEach { child ->
                    // merge inserts children directly: there is no container to receive the include ID.
                    val childLayouts = layouts[child.layout]
                    if (child.id != null && (childLayouts == null || childLayouts.any { !it.isMerge })) {
                        add(child.id, "android.view.View")
                        if (childLayouts == null || childLayouts.all { !it.isMerge }) present += child.id
                    }
                }
                val ownViews = layout.views
                ownViews.forEach(::add)
                present += ownViews.keys
                required = required?.intersect(present) ?: present
            }
            require(merged.keys.groupBy { it.name }.values.none { it.size > 1 }) {
                "$name contains both framework and module IDs with the same name"
            }
            val hasDefault = alternatives.any { it.isDefault }
            optionalIds[name] = if (hasDefault) merged.keys - required.orEmpty() else merged.keys.toSet()
            return merged
        }
        val files = sortedMapOf<String, String>()
        val layoutContainers = types.contains("kotlinx.android.extensions.LayoutContainer")
        for (name in layouts.keys.sorted()) {
            require(identifier.matches(name)) { "Unsupported layout name: $name" }
            val views = resolve(name)
            val path = "kotlinx/android/synthetic/main/$name"
            files["$path/synthetic.kt"] = render(spec, name, views, optionalIds.getValue(name), false,
                layoutContainers)
            files["$path/view.kt"] = render(spec, name, views, optionalIds.getValue(name), true)
        }
        Files.createDirectories(spec.output)
        files.forEach { (relative, text) -> writeIfChanged(spec.output.resolve(relative), text) }
        // Only remove this generator's files, never unrelated user files.
        Files.walk(spec.output).use { paths ->
            paths.filter { Files.isRegularFile(it) && it.fileName.toString().endsWith(".kt") }.forEach { file ->
                val relative = spec.output.relativize(file).toString().replace('\\', '/')
                if (relative !in files && Files.readString(file).startsWith(HEADER)) Files.delete(file)
            }
        }
        return diagnostics.toList()
    }

    private fun parse(file: Path, spec: GenerationSpec, types: ViewTypes): Layout {
        val factory = DocumentBuilderFactory.newInstance().apply {
            isNamespaceAware = true
            setFeature("http://apache.org/xml/features/disallow-doctype-decl", true)
            setFeature("http://xml.org/sax/features/external-general-entities", false)
            setFeature("http://xml.org/sax/features/external-parameter-entities", false)
            setAttribute(XMLConstants.ACCESS_EXTERNAL_DTD, "")
            setAttribute(XMLConstants.ACCESS_EXTERNAL_SCHEMA, "")
        }
        val document = try { Files.newInputStream(file).use { factory.newDocumentBuilder().parse(it) } }
        catch (e: Exception) { throw IllegalArgumentException("Cannot parse layout $file: ${e.message}", e) }
        val documentRoot = document.documentElement
        val layoutRoot = if (documentRoot.tagName == "layout") {
            (0 until documentRoot.childNodes.length).mapNotNull { documentRoot.childNodes.item(it) as? Element }
                .firstOrNull { it.tagName != "data" }
        } else documentRoot
        val views = linkedMapOf<Id, String>()
        val includes = mutableListOf<Include>()
        val nodes = document.getElementsByTagName("*")
        for (index in 0 until nodes.length) {
            val element = nodes.item(index) as Element
            val rawId = element.getAttributeNS(ANDROID, "id")
            val id = if (rawId.isEmpty()) null else {
                require(rawId.matches(Regex("@\\+?(android:)?id/[A-Za-z_][A-Za-z0-9_]*"))) { "$file: unsupported ID '$rawId'" }
                Id(rawId.substringAfter('/'), rawId.contains("android:"))
            }
            val tag = element.tagName
            if (tag == "include") {
                val layout = element.getAttribute("layout")
                require(layout.startsWith("@layout/")) { "$file: unsupported include '$layout'" }
                includes += Include(layout.substringAfter('/'), id)
                continue
            }
            if (id == null) continue
            require(tag != "fragment") { "$file: <fragment> synthetic properties are not supported; use FragmentContainerView or FragmentManager." }
            val type = when (tag) {
                "view" -> resolveType(element.getAttribute("class"), spec, types)
                "merge", "layout", "data", "variable", "import", "requestFocus", "tag" -> continue
                else -> resolveType(tag, spec, types)
            }
            val previous = views.putIfAbsent(id, type)
            require(previous == null || previous == type) { "$file: conflicting types for '${id.name}'" }
        }
        return Layout(views, includes, layoutRoot?.tagName == "merge", file.parent.fileName.toString() == "layout")
    }

    private fun resolveType(tag: String, spec: GenerationSpec, types: ViewTypes): String {
        spec.typeOverrides[tag]?.let {
            require(it.matches(Regex("[A-Za-z_][A-Za-z0-9_.]*(<\\*(,\\s*\\*)*>)?"))) { "Invalid type override: $it" }
            return it
        }
        require(tag.split('.', '$').all { identifier.matches(it) }) { "Unsupported view class '$tag'; expected a qualified class name (nested classes may use $)." }
        val name = when {
            '.' in tag -> tag
            tag == "WebView" -> "android.webkit.WebView"
            tag in setOf("View", "ViewGroup", "SurfaceView", "ViewStub", "TextureView") -> "android.view.$tag"
            else -> "android.widget.$tag"
        }
        return types.resolve(name)
    }

    private fun quoted(name: String) = "`$name`"
    private fun render(spec: GenerationSpec, layout: String, views: Map<Id, String>, optional: Set<Id>, viewOnly: Boolean, layoutContainers: Boolean = false): String = buildString {
        appendLine(HEADER)
        appendLine("@file:Suppress(\"DEPRECATION\")")
        appendLine("package kotlinx.android.synthetic.main.${quoted(layout)}${if (viewOnly) ".view" else ""}")
        appendLine()
        if (views.keys.any { it !in optional }) {
            // An unbounded type parameter allows null through without a runtime non-null assertion.
            appendLine("@Suppress(\"UNCHECKED_CAST\")")
            appendLine("private fun <T> syntheticCompatView(value: Any?): T = value as T")
            appendLine()
        }
        val receivers = if (viewOnly) listOf("android.view.View" to "this") else buildList {
            add("android.app.Activity" to "this")
            add("android.app.Dialog" to "this")
            if (spec.androidX) add("androidx.fragment.app.Fragment" to "view")
            if (spec.platformFragments) add("android.app.Fragment" to "view")
            if (layoutContainers) add("kotlinx.android.extensions.LayoutContainer" to "containerView")
        }
        val namespace = spec.namespace.split('.').joinToString(".", transform = ::quoted)
        for ((receiver, root) in receivers) {
            val nullableRoot = root == "view" || root == "containerView"
            for ((id, type) in views.entries.sortedBy { it.key.name }) {
                val r = if (id.framework) "android.R" else "$namespace.R"
                // Preserve ID case in JVM names (foo/Foo would otherwise both become getFoo).
                appendLine("@get:kotlin.jvm.JvmName(\"synthetic_${id.name}\")")
                appendLine("val $receiver.${quoted(id.name)}: $type${if (id in optional) "?" else ""}")
                if (id in optional && !id.framework) {
                    appendLine("    get() {")
                    appendLine("        val root = $root${if (nullableRoot) " ?: return null" else ""}")
                    appendLine("        val context = ${if (receiver == "android.app.Activity") "root" else "root.context"}")
                    appendLine("        val resources = context.resources")
                    appendLine("        val id = resources.getIdentifier(\"${id.name}\", \"id\", \"${spec.namespace}\").let { if (it != 0) it else resources.getIdentifier(\"${id.name}\", \"id\", context.packageName) }")
                    appendLine("        return if (id == 0) null else root.findViewById<$type>(id)")
                    appendLine("    }")
                } else if (id in optional) {
                    appendLine("    get() = $root${if (nullableRoot) "?" else ""}.findViewById<$type>($r.id.${quoted(id.name)})")
                } else {
                    appendLine("    get() = syntheticCompatView($root${if (nullableRoot) "?" else ""}.findViewById<$type>($r.id.${quoted(id.name)}))")
                }
                appendLine()
            }
        }
    }

    internal fun writeIfChanged(path: Path, text: String) {
        if (Files.exists(path) && Files.readString(path) == text) return
        Files.createDirectories(path.parent)
        val temp = Files.createTempFile(path.parent, ".synthetic-", ".tmp")
        try {
            Files.writeString(temp, text)
            try { Files.move(temp, path, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING) }
            catch (_: java.nio.file.AtomicMoveNotSupportedException) { Files.move(temp, path, StandardCopyOption.REPLACE_EXISTING) }
        } finally { Files.deleteIfExists(temp) }
    }
}
